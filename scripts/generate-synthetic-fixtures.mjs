const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FIXTURES_DIR = path.join(__dirname, '../test/fixtures');
const FIXED_TIMESTAMP = 1755252000; // 2025-08-15T10:00:00Z — frozen so recorded-style tests can pin the clock

function bytesToBase64(bytes) {
  return Buffer.from(bytes).toString('base64');
}

async function writeFixture(
  provider,
  name,
  { credentials, signCredentials, body, signOpts, expected, url, method, extraHeaders },
) {
  const adapter = { stripe, github, shopify, standard, slack, discord, twilio, paddle }[provider];
  const signer = createTestSigner(adapter, signCredentials ?? credentials);
  const signed = await signer.sign(body, { ...signOpts, url });
  const fixture = {
    provider,
    synthetic: true,
    note:
      'SYNTHETIC — generated by createTestSigner, not captured from a real provider delivery. ' +
      'See test/fixtures/README.md for why, and the capture process to replace this.',
    credentials,
    url,
    method: method ?? 'POST',
    headers: { ...signed.headers, ...extraHeaders },
    bodyBase64: bytesToBase64(signed.body),
    expected,
  };
  writeFileSync(
    path.join(FIXTURES_DIR, provider, `${name}.json`),
    `${JSON.stringify(fixture, null, 2)}\n`,
  );
  console.log(`wrote ${provider}/${name}.json`);
}

